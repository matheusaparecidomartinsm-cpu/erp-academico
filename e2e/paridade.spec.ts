import { test, expect, alerta } from './fixtures'

test('PAR-1 tabela de preço: criar, definir preço e ver no pedido do cliente vinculado', async ({ page }) => {
  await page.goto('/tabelas-preco')
  await page.getByRole('button', { name: 'Nova tabela' }).first().click()
  await page.getByLabel('Nome').fill('Atacado')
  await page.getByRole('button', { name: 'Criar tabela' }).click()
  await page.getByRole('link', { name: 'Atacado' }).click()
  const linha = page.getByRole('row').filter({ hasText: /\w/ }).nth(1)
  const nomeProduto = (await linha.getByRole('rowheader').innerText()).trim()
  await linha.getByRole('textbox').fill('1,00')
  await linha.getByRole('button', { name: /Salvar preço/ }).click()
  await expect(page.getByRole('button', { name: /Remover preço de/ })).toBeVisible()
  // vincula ao cliente
  await page.goto('/clientes/cli-1')
  await page.getByLabel('Tabela de preço').selectOption({ label: 'Atacado' })
  await page.getByRole('button', { name: 'Salvar' }).click()
  await expect(alerta(page)).toHaveCount(0)
  // pedido usa o preço da tabela
  await page.goto('/pedidos/novo')
  await page.getByLabel('Cliente').selectOption({ label: 'Mercado Exemplo Ltda' })
  await page.getByLabel('Produto').selectOption({ label: nomeProduto })
  await page.getByLabel('Qtd.').fill('1')
  await expect(page.getByText(/R\$\s*1,00/).first()).toBeVisible()
})

