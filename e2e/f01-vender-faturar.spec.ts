test('F01-E8 duas abas: confirmar o mesmo pedido duas vezes não duplica', async ({ context }) => {
  const a = await context.newPage(); await novoPedido(a, 'Padaria Modelo ME', 'Bandeja de papel-cartão 500 g', '1', false)
  const b = await context.newPage(); await b.goto(a.url())
  await a.getByRole('button', { name: 'Confirmar pedido' }).click(); await expect(a.getByText('Confirmado').first()).toBeVisible()
  await b.getByRole('button', { name: 'Confirmar pedido' }).click()
  await b.goto('/estoque')
  await expect(b.locator('tr', { hasText: 'Bandeja de papel-cartão 500 g' }).first()).toContainText('60') // 1 pedido confirmado não baixa; baixa só no faturamento
})
