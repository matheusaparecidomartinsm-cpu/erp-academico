import { test, expect, novoPedido, faturar } from './fixtures'

test('F01-H1 vender, faturar em 3 parcelas e ver a receber', async ({ page }) => {
  await novoPedido(page, 'Padaria Modelo ME', 'Bandeja de papel-cartão 500 g', '10')
  await expect(page.getByText('Confirmado').first()).toBeVisible()
  await faturar(page, '3')
  await expect(page.getByText('Parcelas a receber')).toBeVisible()
  await expect(page.getByText('1/3')).toBeVisible()
  await page.goto('/estoque')
  await expect(page.locator('tr', { hasText: 'Bandeja de papel-cartão 500 g' }).first()).toContainText('50')
})
test('F01-E1 sem estoque: mensagem clara e pedido não avança', async ({ page }) => {
  await novoPedido(page, 'Lanchonete Teste', 'Fita adesiva 48 mm', '5')
  await expect(page.getByText('Saldo insuficiente').first()).toBeVisible()
  await expect(page.getByText('Confirmado')).toHaveCount(0)
})
test('F01-E2 cliente bloqueado não vende', async ({ page }) => {
  await page.goto('/pedidos/novo')
  await page.getByLabel('Cliente').selectOption({ label: 'Restaurante Fictício Ltda (bloqueado)' })
  await page.getByLabel('Produto').selectOption({ label: 'Bandeja de papel-cartão 500 g' })
  await page.getByLabel('Qtd.').fill('1')
  await page.getByRole('button', { name: 'Salvar e confirmar' }).click()
  await page.waitForURL(/\/pedidos\/ped-\d+/)
  await expect(page.getByText(/bloqueado/i).first()).toBeVisible()
  await expect(page.getByText('Confirmado')).toHaveCount(0)
})
test('F01-E3 duplo clique em Salvar cria um só pedido', async ({ page }) => {
  await page.goto('/pedidos')
  await expect(page.getByRole('row').nth(1)).toBeVisible()
  const antes = await page.getByRole('row').count()
  await page.goto('/pedidos/novo')
  await page.getByLabel('Cliente').selectOption({ label: 'Padaria Modelo ME' })
  await page.getByLabel('Produto').selectOption({ label: 'Bandeja de papel-cartão 500 g' })
  await page.getByLabel('Qtd.').fill('1')
  await page.getByRole('button', { name: 'Salvar e confirmar' }).dblclick()
  await page.waitForURL(/\/pedidos\/ped-\d+/)
  await page.goto('/pedidos')
  await expect(page.getByRole('row')).toHaveCount(antes + 1)
})
test('F01-E4 recarregar no meio do faturamento mantém o pedido confirmado', async ({ page }) => {
  await novoPedido(page, 'Padaria Modelo ME', 'Bandeja de papel-cartão 500 g', '2')
  await page.getByRole('button', { name: 'Faturar' }).click()
  await page.reload()
  await expect(page.getByText('Confirmado').first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Faturar' })).toBeVisible()
})
test('F01-E5 observação longa com emoji e acento não quebra o layout', async ({ page }) => {
  await page.goto('/pedidos/novo')
  await page.setViewportSize({ width: 390, height: 800 })
  await page.getByLabel('Cliente').selectOption({ label: 'Padaria Modelo ME' })
  await page.getByLabel('Produto').selectOption({ label: 'Bandeja de papel-cartão 500 g' })
  await page.getByLabel('Qtd.').fill('1')
  await page.getByLabel('Observação (opcional)').fill('Entrega às 7h — ação urgente 🚚 ' + 'x'.repeat(200))
  await page.getByRole('button', { name: 'Salvar como rascunho' }).click()
  await page.waitForURL(/\/pedidos\/ped-\d+/)
  const w = await page.evaluate(() => [document.documentElement.scrollWidth, document.documentElement.clientWidth])
  expect(w[0]).toBeLessThanOrEqual(w[1])
})
test('F01-E6 quantidade zero, negativa ou vazia é recusada', async ({ page }) => {
  for (const q of ['0', '-3', '']) {
    await page.goto('/pedidos/novo')
    await page.getByLabel('Cliente').selectOption({ label: 'Padaria Modelo ME' })
    await page.getByLabel('Produto').selectOption({ label: 'Bandeja de papel-cartão 500 g' })
    await page.getByLabel('Qtd.').fill(q)
    await page.getByRole('button', { name: 'Salvar como rascunho' }).click()
    await expect(page, `qtd=${q}`).toHaveURL(/pedidos\/novo/)
  }
})
